package com.aiagent.domain.batch;

/**
 * 실행 결과 — 46 §6.1 · 65 §4.3. <b>일곱이고, 공통코드가 아니다.</b>
 *
 * <p>65 §2.3 이 {@code SYS_CODE} 에 두지 않기로 하며 근거를 넷 들었다: 값을 아는 것은
 * <b>러너의 분기</b>이고, 관리자가 늘릴 일이 없으며, 늘리려면 소스를 고쳐야 하고,
 * 공통코드로 두면 {@code SYS_YN='Y'} 로 잠가야 하는데(43 §4.3) <b>잠가 두면 관리자에게
 * 남는 것이 없다</b>. 라벨만 메시지 키({@code batch.rslt.*})다.
 *
 * <h2>{@code SKIP} 이 둘로 갈린 것이 이 열거형의 요점이다</h2>
 *
 * <p>처음에는 하나였고 사유를 {@code RSLT_MSG} 에 넣기로 했다. 화면을 그려 보니 <b>한
 * 코드에 정상과 결함이 함께</b> 있었다.
 *
 * <table><caption></caption>
 *   <tr><td>{@link #SKIP_LOCK}</td><td><b>정상</b> — 다중화에서 한 노드만 실행한다</td>
 *       <td>노드 수 − 1 만큼 <b>매 주기</b></td></tr>
 *   <tr><td>{@link #SKIP_COOLDOWN}</td><td><b>결함</b> — 31 §7 이 막으려던 사고다</td>
 *       <td><b>나면 안 된다</b></td></tr>
 * </table>
 *
 * <p><b>{@code RSLT_MSG} 로 분기하지 않는다.</b> 문자열을 화면이 읽어 색을 정하면 문구를
 * 고치는 순간 화면이 틀린다 — 45 §5.1 이 로그인 실패를 체인 지점마다 코드로 가른 것과
 * 같은 규칙이다. 사유는 {@code RSLT_MSG} 에 계속 적되 <b>판정은 코드가 갖는다</b>.
 *
 * <p><b>{@code USE_YN='N'} 은 어느 코드도 아니다</b>(65 §3.6) — 스케줄러가 등록하지 않으므로
 * <b>행이 없다</b>. 실행 이력에서 행이 없으면 꺼져 있는 것이고 {@code SKIP_*} 이 있으면
 * 켜져 있는데 건너뛴 것이다.
 */
public enum BatchResultCode {

    /**
     * 시작 시 INSERT 되고 종료 시 갱신된다 — <b>이력인데 갱신되는 유일한 테이블</b>이
     * 되는 이유다(46 §6).
     *
     * <p>미리 넣지 않으면 프로세스가 죽었을 때 <b>흔적이 없고</b>, 그러면 <i>실행 자체가
     * 없었던 것</i> 과 구분되지 않는다. 그 죽은 행을 {@link #LOST} 로 바꾸는 것이
     * {@code BatchGhostSweeper} 다 — 이 상태로 <b>영원히</b> 남는 행은 이제 없다.
     */
    RUNNING,

    SUCCESS,

    /** 예외로 종료 — {@code ERR_MSG} 를 채운다. */
    FAIL,

    /** <b>락 선점 실패</b> — 다른 노드가 가져갔다. 다중화에서는 <b>정상</b>이다. */
    SKIP_LOCK,

    /** <b>쿨다운에 막힘</b> — 31 §7 이 막으려던 사고이며 <b>나면 안 된다</b>. */
    SKIP_COOLDOWN,

    /** 사람이 중단시켰고 <b>배치가 그것을 읽었다</b> — 46 §6.2. */
    CANCELED,

    /**
     * <b>실행하던 노드가 사라졌다</b> — 결과를 아무도 적지 못했다(65 §4.4).
     *
     * <p>{@code RUNNING} 행은 실행 스레드가 갱신한다. 그 스레드가 있던 <b>프로세스가
     * 통째로 죽으면</b> 갱신할 주체가 없어 행이 영원히 {@code RUNNING} 으로 남고, 그것이
     * 65 §4.4 가 <b>유령</b>이라 부른 것이다. 유령은 눈에 거슬리는 데서 그치지 않는다 —
     * {@code runNow} 가 <i>이미 실행 중</i> 으로 읽어 <b>그 배치를 영원히 못 돌리게</b> 한다.
     *
     * <h2>{@code FAIL} 이 아닌 이유</h2>
     *
     * <p>{@code FAIL} 은 <b>배치가 예외를 던졌다</b>는 뜻이고 그 증거가 {@code ERR_MSG} 의
     * 스택이다. 여기에는 스택이 없다 — 죽은 것은 배치가 아니라 <b>프로세스</b>이며, 배치가
     * 어디까지 했는지 <b>아무도 모른다</b>. 같은 코드로 두면 스택을 찾다 못 찾은 사람이
     * <i>로그가 유실됐다</i> 고 결론짓는다.
     *
     * <p><b>{@code ELAPSED_MS} 가 {@code null}</b> 인 것도 같은 이유다. 판정 시각까지를
     * 소요로 적으면 <i>3일 걸린 배치</i> 가 되어 소요 정렬을 통째로 망친다 — 모르는 것을
     * 0 이나 큰 수로 적지 않는다.
     *
     * <p><b>판정은 락이 한다.</b> 시각으로 재지 않는다 — 오래 도는 배치는 정상이고,
     * 그것을 죽었다고 부르는 임계값은 존재하지 않는다. 살아 있는 노드는 락의
     * {@code EXPIRE_DTM} 을 계속 밀어 주므로(하트비트, 31 §5.1), <b>락이 없다</b>가
     * 곧 <b>그 프로세스가 없다</b>이다.
     */
    LOST;

    /** 진행 중인가 — 중단 대상 판정과 유령 판정이 함께 본다(65 §4.4 · §4.5). */
    public boolean isRunning() {
        return this == RUNNING;
    }

    /**
     * 끝났는가 — <b>{@code SKIP_*} 도 끝난 것</b>이다.
     *
     * <p>시작조차 하지 않았지만 <b>그 실행 시도는 종결됐다</b>(46 §6.1 의 전이표에서
     * {@code RUNNING} 을 거치지 않는 두 갈래다). 이 구분이 필요한 자리는 러너이며,
     * 여기서 {@code SKIP_*} 을 <i>진행 중</i> 으로 읽으면 다음 주기가 자기 앞의
     * 건너뜀을 <b>실행 중</b> 으로 오인한다.
     */
    public boolean isFinished() {
        return this != RUNNING;
    }

    /**
     * 건너뛴 것인가 — <b>쿨다운의 기준을 고르는 데 쓴다</b>(31 §5).
     *
     * <p>건너뜀은 <i>시도했다</i> 는 기록이지 <b>실행이 아니다</b>. 재실행 간격은 실행과
     * 실행 사이의 거리이므로 기준에서 빠져야 하며, 넣으면 {@code SKIP_COOLDOWN} 이
     * <b>자기 다음 판정의 기준</b>이 되어 쿨다운이 주기마다 앞으로 밀린다 — 그 배치는
     * 다시는 돌지 않는다({@code BatchRunner#cooldownUntil} 참조).
     */
    public boolean isSkipped() {
        return this == SKIP_LOCK || this == SKIP_COOLDOWN;
    }
}
