package com.ordinary.backoffice.domain.batch;

/**
 * 배치 한 종류 — BATCH-09. <b>사용 프로젝트가 구현한다.</b>
 *
 * <p>템플릿에는 <b>업무 배치</b>가 하나도 없다. 지어내면 아무도 안 쓰는 배치가 시드에 남고,
 * 그것은 004 가 역할을 {@code ADMIN} 하나로 둔 것과 같은 판단이다.
 *
 * <p><b>시스템 배치는 다르다.</b> 보존 파기({@code RetentionPurgeJob} · LOG-07)가 하나 있고,
 * 그것은 지어낸 것이 아니라 32 가 <b>이미 정책으로 정해 둔</b> 기능이다 — 없으면 이력
 * 테이블이 무한히 자란다. 그래서 스케줄 관리 화면의 {@code BEAN_ID} 셀렉트에는 <b>값이
 * 하나</b> 있고, 사용 프로젝트가 늘리는 것은 그 옆이다(65 §3.3).
 *
 * <h2>빈 이름이 곧 {@code BEAN_ID} 다</h2>
 *
 * <p>{@link BatchJobRegistry} 가 스프링 컨텍스트에서 이 인터페이스의 구현을 모아 셀렉트
 * 목록을 만든다. <b>등록 여러 건이 같은 구현을 가리켜도 된다</b> — 46 §5.2 의 창고 10개가
 * 그것이며, 파라미터만 다른 등록 열 건이 {@code inventoryCloseJob} 하나를 쓴다.
 *
 * <h2>{@code paramJson} 을 파싱하지 않고 그대로 준다</h2>
 *
 * <p>46 §5.2 가 <i>"스펙은 코드가 갖고 DB 는 값만 담는다"</i> 고 정했다. 어떤 키를 받고
 * 무엇이 필수인지는 <b>구현이 이미 아는 사실</b>이며, 여기서 {@code Map} 으로 풀어 주면
 * 프레임워크가 그 스펙의 절반을 갖게 된다 — 타입도 필수 여부도 모른 채로. 문자열을
 * 넘기고 구현이 자기 레코드로 읽는 것이 <b>규칙이 한 곳에 남는</b> 유일한 모양이다.
 *
 * <h2>취소는 <b>물어보는 쪽</b>이 협조해야 성립한다</h2>
 *
 * <p>65 §4.5 · 46 §6.2 — 배치는 <b>다른 노드에서 돌 수 있으므로</b> 스레드를 직접 끊을 수
 * 없다. {@link BatchJobContext#isCancelRequested()} 를 체크포인트마다 읽고 스스로 멈추는
 * 것이 <b>이 인터페이스의 계약</b>이며, 읽지 않는 구현은 끝까지 돌고 {@code SUCCESS} 로
 * 끝난다 — <b>화면은 그것을 거짓말하지 않는다</b>(46 §6.2 표의 넷째 줄).
 *
 * <p><b>멈췄으면 멈췄다고 말해야 한다</b> — {@link BatchJobResult#canceled(String)} 이다.
 * 그냥 {@code of(...)} 로 돌려주면 러너는 <i>확인하지 않고 끝까지 돈 배치</i> 와 구분할
 * 수 없고, 그 구분이 46 §6.2 표의 셋째 줄과 넷째 줄이다.
 *
 * <p><b>확인하지 않는 구현을 빌드가 막지 못한다</b>(65 §6 의 미결). 인터페이스로 표현할 수
 * 있는 것은 <i>물어볼 수단을 준다</i> 까지이며, <i>물어봤는가</i> 는 정적으로 알 수 없다.
 * 그래서 여기서는 <b>계약을 문서로 못박고</b> 화면이 그 결과를 정직하게 그리는 쪽을 택했다.
 *
 * <h2>예외를 삼키지 않는다</h2>
 *
 * <p>던지면 {@code FAIL} 이고 스택이 {@code ERR_MSG} 에 남는다(46 §6.1). 구현이
 * {@code try/catch} 로 감싸 정상 종료로 만들면 <b>실행 이력이 성공으로 남고</b> 실패
 * 알림(BATCH-06)도 나가지 않는다 — 원칙 P1 의 <i>실패가 시끄러운 쪽</i> 이 여기서 깨진다.
 */
public interface BatchJob {

    /**
     * 한 번의 실행.
     *
     * @param context 파라미터와 <b>취소 여부를 묻는 수단</b>
     * @return 요약 · 상세 · <b>중단 여부</b> — {@code null} 을 돌려줘도 된다
     *     ({@link BatchJobResult#empty()} 와 같다)
     * @throws Exception 던지면 {@code FAIL} 이다. <b>삼키지 않는다</b>
     */
    BatchJobResult run(BatchJobContext context) throws Exception;
}
