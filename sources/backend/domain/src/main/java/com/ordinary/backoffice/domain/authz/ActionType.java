package com.ordinary.backoffice.domain.authz;

/**
 * 액션 4종 — security-design.md §4. <b>집합은 여기서 닫힌다.</b>
 *
 * <p>화면별 커스텀 액션을 허용하면 권한 화면이 메뉴마다 다른 컬럼을 갖게 되어
 * (주체 × 메뉴 × 액션) 의 균일함이 깨진다.
 *
 * <p><b>등록·수정·삭제로 쪼개지 않는다.</b> 그리드 저장 표준이 리스트 CUD 일괄 처리(UX-14)이고,
 * 행별 구분은 URL 이 아니라 <b>페이로드 안에</b> 있다 — 셋으로 쪼개 판정하려면 서비스가
 * 페이로드를 열어야 하고, 그러면 판정을 인터셉터 한 곳에 두는 원칙이 깨진다.
 * <b>서버가 API 경계에서 집행할 수 없는 세분 권한은 권한 화면의 장식일 뿐이다.</b>
 */
public enum ActionType {

    /** 조회 — 화면 진입, 목록·상세. 나머지 셋의 전제다(42 §6). */
    READ,

    /** 저장 — <b>추가·수정·삭제를 포함한다.</b> */
    SAVE,

    /** 출력 — 엑셀 다운로드. */
    EXPORT,

    /**
     * 절차 발동 — 배치 수동 실행, 승인/반려, 발송, 마감, 강제 로그아웃.
     *
     * <p>이것이 없으면 위험한 버튼이 {@code SAVE} 에 섞여 <i>"저장 권한을 주면 배치 실행도
     * 된다"</i> 가 된다. 실무에서 필요한 비대칭은 "수정 vs 삭제" 가 아니라
     * <b>"일상 저장 vs 위험한 절차"</b> 다.
     */
    EXECUTE
}
