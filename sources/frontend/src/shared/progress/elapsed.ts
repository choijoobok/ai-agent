/**
 * 진행률 창이 <b>뜬 지 얼마나 지났는가</b> — 30 §6 · 68 §9.1.
 *
 * <p><b>퍼센트만으로는 기다릴 수 없다.</b> 24% 는 <i>얼마나 더</i> 를 말하지 않는데,
 * 사용자가 그 창 앞에서 실제로 하는 결정은 <b>기다릴까 접을까</b> 하나다 — 3초 지난
 * 24% 와 5분 지난 24% 는 그 결정이 정반대다.
 *
 * <p><b>시각을 서버에서 받지 않는다.</b> {@code CRE_DTM} 을 쓰면 브라우저와 서버의 시계가
 * 어긋난 만큼 이 숫자가 틀리고(음수까지 나온다), 더 나쁜 것은 <b>폴링이 실패하는 동안
 * 멈춘다</b>는 점이다 — 진행률을 못 보는 그 구간이 바로 경과 시간이 가장 필요한 때다.
 * 그래서 기준은 <b>창을 연 순간</b>이며, 그 값은 호스트가 들고 있다({@code openedAt}).
 *
 * <p><b>분과 초다.</b> 시간 단위를 두지 않은 것은 이 창이 그렇게 오래 열려 있으면
 * <i>접어 두는 것</i>이 답이기 때문이고(68 §9.1), 90분짜리는 {@code 90분 12초} 로
 * 읽힌다 — 세 자리가 되는 편이 <b>단위가 하나 늘어 눈이 다시 읽는 것</b>보다 낫다.
 */

/**
 * {@code progress.elapsed} 의 자리표 — 문구는 서버가 갖는다(43 §3).
 *
 * <p><b>{@code interface} 가 아니라 별칭이다.</b> {@code label()} 의 자리표는
 * {@code Record<string, string | number>} 이고, 타입스크립트는 <b>별칭에만</b> 암묵적
 * 인덱스 시그니처를 준다 — {@code interface} 로 두면 그 인자 자리에서 컴파일이 막힌다.
 */
export type Elapsed = {
  min: number;
  /** <b>두 자리로 채운다</b> — 폭이 흔들리면 1초마다 그 줄이 움직인다. */
  sec: string;
};

export function splitElapsed(ms: number): Elapsed {
  /*
    <b>음수를 0 으로 접는다.</b> 시계가 뒤로 갈 수 있다(NTP 보정 · 사용자가 고친 시각) —
    그때 `-1분 -3초` 를 보이는 것은 진행률의 신뢰를 통째로 깎는다.
  */
  const seconds = Math.max(0, Math.floor(ms / 1000));
  return { min: Math.floor(seconds / 60), sec: String(seconds % 60).padStart(2, '0') };
}
